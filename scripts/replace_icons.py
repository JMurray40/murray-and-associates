# regex matches any emoji key optionally followed by a variation selector (U+FE0F)
pattern = re.compile('(' + '|'.join(re.escape(k) for k in ICONS) + ')\ufe0f?')
def repl(m):
    return svg(ICONS[m.group(1)])

# per-file copy fixes (True = exact string replacements)
COPY_FIXES = {
    'index.html': [('<div class="stat-num">10+</div>', '<div class="stat-num">20+</div>')],
    'consultation.html': [
        ('10+ years serving small businesses', '20+ years serving small businesses'),
        ('free 30-minute consultation', 'free 15-minute consultation'),
    ],
    'services.html': [('free 30-minute consultation', 'free 15-minute consultation')],
}

base = '/app'
changed = []
for path in glob.glob(os.path.join(base, '*.html')):
    with open(path, 'r', encoding='utf-8') as f:
        text = f.read()
    new = pattern.sub(repl, text)
    fname = os.path.basename(path)
    for old, rep in COPY_FIXES.get(fname, []):
        if old in new:
            new = new.replace(old, rep)
            changed.append(f'{fname}: copy fix "{old[:40]}"')
    if new != text:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(new)
        changed.append(fname + ': icons/updated')

# leftover emoji check (excludes the ✓ U+2713 design glyph and typographic arrows)
import unicodedata
leftovers = {}
for path in glob.glob(os.path.join(base, '*.html')):
    with open(path, 'r', encoding='utf-8') as f:
        t = f.read()
    for ch in set(t):
        cp = ord(ch)
        if cp > 0x2100 and ch not in ('→', '›', '✓', '✕', '—', '–', '’', '…', '\ufe0f'):
            if 0x1F000 <= cp <= 0x1FAFF or 0x2600 <= cp <= 0x27BF or cp in (0x2B50,):
                leftovers.setdefault(os.path.basename(path), set()).add(ch)

print('CHANGED:')
for c in changed:
    print('  ', c)
print('LEFTOVER EMOJI:', {k: ''.join(v) for k, v in leftovers.items()} or 'none')
